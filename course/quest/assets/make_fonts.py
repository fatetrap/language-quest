"""Builds quest/assets/fonts.js: the quest's two pixel fonts as base64 woff2, loaded with the FontFace API (no url(),
no @font-face, no network: works by double-click on file://). Run once when the fonts change:

  npm pack @fontsource/press-start-2p @fontsource/unifont   (in a temp folder, then untar both)
  pyftsubset <unifont>/files/unifont-latin-400-normal.woff2 --flavor=woff2 --output-file=uni.woff2 --unicodes=<UNI below>
  python make_fonts.py <press-start-2p package dir> uni.woff2

Press Start 2P (OFL, Reserved Font Name) ships unmodified: fontsource's latin / cyrillic / cyrillic-ext files.
GNU Unifont (OFL, no reserved name) is subset to Latin, Cyrillic and the symbols the UI uses (~33 KB).
Licenses: OFL-PressStart2P.txt, OFL-Unifont.txt next to this file.
"""
import base64
import sys
from pathlib import Path

UNI = ('U+0020-007E,U+00A0-017F,U+0400-04FF,U+2010-2027,U+2030-205E,U+20AC,U+2116,U+2122,U+2190-21FF,U+2300-23FF,'
       'U+2500-25FF,U+2600-26FF,U+2700-27BF')
PS2P = {  # fontsource's own subsets (unicode.json of @fontsource/press-start-2p)
    'latin': 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
    'cyrillic': 'U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116',
    'cyrillic-ext': 'U+0460-052F,U+1C80-1C8A,U+20B4,U+2DE0-2DFF,U+A640-A69F,U+FE2E-FE2F'}


def b64(p):
    return base64.b64encode(Path(p).read_bytes()).decode('ascii')


def main(ps2p_dir, uni):
    faces = [('Yarya Pixel', b64(Path(ps2p_dir) / 'files' / f'press-start-2p-{k}-400-normal.woff2'), r) for k, r in PS2P.items()]
    faces.append(('Yarya Uni', b64(uni), UNI))
    rows = ',\n'.join(f"  ['{f}', '{r}', '{d}']" for f, d, r in faces)
    js = f"""/* Yarya Quest pixel fonts, generated by make_fonts.py (do not edit). Plain script, no network.
   'Yarya Pixel' = Press Start 2P (SIL OFL 1.1, Reserved Font Name "Press Start 2P", unmodified fontsource files):
     UI chrome, titles, commands. 'Yarya Uni' = GNU Unifont subset (SIL OFL 1.1): every learning text (8x16 bitmap
     glyphs incl. Mongolian Cyrillic Ө ө Ү ү), crisp at 16 / 32 / 48 px. Licenses: OFL-PressStart2P.txt, OFL-Unifont.txt */
(function () {{
  'use strict';
  const FACES = [
{rows}
  ];
  if (typeof FontFace !== 'function' || !document.fonts || typeof atob !== 'function') return;
  for (const [family, range, data] of FACES) {{
    try {{
      const bin = atob(data), buf = new Uint8Array(bin.length);
      for (let i = 0; i < bin.length; i++) buf[i] = bin.charCodeAt(i);
      const f = new FontFace(family, buf.buffer, {{ unicodeRange: range, display: 'block' }});
      document.fonts.add(f); f.load().catch(() => {{}});
    }} catch (e) {{}}
  }}
}})();
"""
    out = Path(__file__).with_name('fonts.js')
    out.write_text(js, encoding='utf-8')
    print(out, len(js))


if __name__ == '__main__':
    main(*sys.argv[1:3])
